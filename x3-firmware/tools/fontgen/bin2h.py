#!/usr/bin/env python3
"""Embeds a binary file (e.g. a TTF) as a C array: bin2h.py <in> <symbol> <out.h>"""
import sys

src, sym, out = sys.argv[1:4]
data = open(src, "rb").read()
with open(out, "w") as f:
    f.write(f"// Generated by tools/fontgen/bin2h.py from {src.split('/')[-1]}. Do not edit.\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write(f"inline constexpr uint32_t {sym}_size = {len(data)};\n")
    f.write(f"alignas(4) inline const uint8_t {sym}[] = {{\n")
    for i in range(0, len(data), 20):
        f.write("  " + ",".join(f"0x{b:02X}" for b in data[i:i + 20]) + ",\n")
    f.write("};\n")
