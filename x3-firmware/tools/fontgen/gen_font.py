#!/usr/bin/env python3
"""Convert a TTF/OTF font into an Adafruit GFX font header with Turkish letters.

Printable ASCII 0x20-0x7E keeps its codes. The Turkish letters and · ° – ₺ are placed
at 0x80-0x8F (see EXTRA below); src/text.cpp maps UTF-8 input to these codes.
Glyphs are rendered with Pillow and thresholded to 1 bit.

Usage: gen_font.py <font-file> <pixel-size> <symbol-name> <out.h> [options...]
  digits     only 0-9 and ':' (for big numbers)
  wght=500   weight for variable fonts
"""
import sys

from PIL import Image, ImageDraw, ImageFont

EXTRA = "ÇçĞğİıÖöŞşÜü·°–₺"  # codes 0x80.. in this order (src/text.cpp mirrors it)
FIRST, LAST = 0x20, 0x80 + len(EXTRA) - 1


def char_for(code):
    if code <= 0x7E:
        return chr(code)
    if code >= 0x80:
        return EXTRA[code - 0x80]
    return None  # 0x7F: empty slot


def main():
    path, size, name, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
    opts = sys.argv[5:]
    charset = "digits" if "digits" in opts else "full"
    font = ImageFont.truetype(path, size)
    for o in opts:
        if o.startswith("wght="):
            font.set_variation_by_axes([int(o[5:])])
    ascent, descent = font.getmetrics()

    bits, glyphs = [], []
    for code in range(FIRST, LAST + 1):
        ch = char_for(code)
        if ch is not None and charset == "digits" and ch not in "0123456789:":
            ch = None
        if ch is None or ch == " ":
            adv = round(font.getlength(" ")) if ch == " " or charset == "digits" else 0
            if charset == "digits" and ch is None:
                adv = 0
            glyphs.append((len(bits) // 8, 0, 0, adv, 0, 0))
            continue
        adv = round(font.getlength(ch))
        pad = size
        img = Image.new("L", (adv + 2 * pad, ascent + descent + 2 * pad), 0)
        ImageDraw.Draw(img).text((pad, pad), ch, font=font, fill=255)
        bbox = img.point(lambda v: 255 if v >= 128 else 0).getbbox()
        if bbox is None:
            glyphs.append((len(bits) // 8, 0, 0, adv, 0, 0))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        offset = len(bits) // 8
        for y in range(y0, y1):
            for x in range(x0, x1):
                bits.append(1 if img.getpixel((x, y)) >= 128 else 0)
        while len(bits) % 8:
            bits.append(0)
        # yOffset: from baseline (pad + ascent) to the glyph's top row.
        glyphs.append((offset, w, h, adv, x0 - pad, y0 - (pad + ascent)))

    data = bytearray()
    for i in range(0, len(bits), 8):
        b = 0
        for bit in bits[i:i + 8]:
            b = (b << 1) | bit
        data.append(b)

    with open(out, "w") as f:
        f.write(f"// Generated by tools/fontgen/gen_font.py from {path.split('/')[-1]} at {size}px {' '.join(opts)}.\n")
        f.write(f"// Extra glyphs at 0x80-0x{LAST:02X}: " + EXTRA + "\n#pragma once\n#include <Adafruit_GFX.h>\n\n")
        f.write(f"const uint8_t {name}Bitmaps[] PROGMEM = {{\n")
        for i in range(0, len(data), 16):
            f.write("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",\n")
        f.write("};\n\n")
        f.write(f"const GFXglyph {name}Glyphs[] PROGMEM = {{\n")
        for g in glyphs:
            f.write("  {%d, %d, %d, %d, %d, %d},\n" % g)
        f.write("};\n\n")
        f.write(f"const GFXfont {name} PROGMEM = {{(uint8_t*){name}Bitmaps, (GFXglyph*){name}Glyphs, "
                f"0x{FIRST:02X}, 0x{LAST:02X}, {ascent + descent}}};\n")


if __name__ == "__main__":
    main()
